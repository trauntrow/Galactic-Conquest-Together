param([Parameter(Mandatory)][string]$Output)
# Builds player_apply.inc: the scripts that save, verify, patch and load a received galaxy on a friend's game.
# Each script is also written next to the output as a .lua file for tests/player_apply_test.lua.
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
function Read-Lua($name) { [IO.File]::ReadAllText((Join-Path $root "src\lua\$name")).Replace("`r`n", "`n") }
function Replace-Once($text, $old, $new, $what) {
    if (([regex]::Matches($text, [regex]::Escape($old))).Count -ne 1) { throw "$what not found exactly once" }
    $text.Replace($old, $new)
}

# Argument 3 arrives as the host's hints and becomes this PC's own profile on the right team.
$prepare = Read-Lua 'runtime_prepare.lua'
$anchor = "    assert(type(ScriptCB_GetProfileName) == 'function' and type(ScriptCB_ununicode) == 'function')`n"
$fill = $anchor +
    "    -- The host's hints: its human team, the planet its camera shows and the zoom.`n" +
    "    local hints = expected[3]`n" +
    "    local human = hints[1]`n" +
    "    assert(human == 1 or human == 2)`n" +
    "    -- In Versus this PC plays the other side.`n" +
    "    local versus = type(ScriptCB_IsFileExist) == 'function' and ScriptCB_IsFileExist('GCOBS:ask:versus') == 1`n" +
    "    if versus then human = 3 - human end`n" +
    "    expected[3] = {[ScriptCB_ununicode(ScriptCB_GetProfileName(1))] = human}`n"
$prepare = Replace-Once $prepare $anchor $fill 'profile anchor'
$prepare = Replace-Once $prepare 'expected[3][profile] == expected[13])' 'expected[3][profile] == human)' 'profile check'

# Everything before the save is shared with the verify, live and patch scripts.
$boundary = '    -- Save only; the copy is verified before anything loads it.'
$at = $prepare.IndexOf($boundary)
if ($at -lt 0) { throw 'missing serialization boundary' }
$prefix = $prepare.Substring(0, $at)
$save = "    ScriptCB_SaveMetagameState(unpack(expected))"
if (-not $prepare.Contains($save)) { throw 'missing save call' }
# Only the host's turn gets loaded (either side in Versus); loading the AI's turn would start the AI here.
$hostTurn = "    assert(expected[13] == human or versus)`n"
$scripts = [ordered]@{
    player_prepare_query = $prepare.Replace($save, $hostTurn + $save)
    player_repeat_prepare_query = $prepare.Replace($save, $hostTurn +
        "    assert(ifs_freeform_main.scenario == expected[2])`n" + $save)
    player_verify_query = $prefix + (Read-Lua 'runtime_verify_body.lua')
    player_live_query = $prefix + (Read-Lua 'runtime_live_body.lua')
    player_patch_query = $prefix + (Read-Lua 'player_patch_body.lua')
    player_dispatch_query = "assert(type(ifs_freeform_load_LoadMetagameSuccess) == 'function')`nifs_freeform_load_LoadMetagameSuccess()`nreturn 6217431`n"
}

$dir = Split-Path -Parent ([IO.Path]::GetFullPath($Output))
$header = "// Generated by tools/embed-player-apply.ps1 from src/lua/runtime_*.lua; do not edit.`n"
foreach ($name in $scripts.Keys) {
    $source = $scripts[$name]
    if ($source.Contains(')GCTAPPLY"')) { throw 'C++ raw literal delimiter occurs in script' }
    $header += "constexpr char $name[] = R`"GCTAPPLY($source)GCTAPPLY`";`n"
    $file = Join-Path $dir (($name -replace '_query$', '') + '.lua')
    [IO.File]::WriteAllText($file, $source, [Text.Encoding]::ASCII)
}
[IO.File]::WriteAllText([IO.Path]::GetFullPath($Output), $header, [Text.Encoding]::ASCII)
